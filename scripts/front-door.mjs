// The public HTTPS front door (settings.exposure: public; docs/design/access.md, Exposure modes): Caddy on the host's
// 443 with a Let's Encrypt certificate for the server's public IPv4 (the `shortlived` profile, TLS-ALPN-01 only: port 80
// stays closed), reverse-proxying to the board's browser listener on loopback. Compile writes config/Caddyfile and the
// host-networked `caddy` service from the host's AIDENHQ_PUBLIC_IP (.env: setup detects it, the owner may override it).
//   node scripts/front-door.mjs detect        the default route's public IPv4, or exit 1 saying why there is none
//   node scripts/front-door.mjs wait <ip> [s]  wait (default 180 s) for https://<ip> to answer with a publicly trusted
//                                              certificate (curl, the system's trust store); exit 1 if it never does
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

export const BOARD_UPSTREAM = "127.0.0.1:3121"; // the board's browser listener (compose.yaml: published on loopback only)
export const EDGE_SECRET_FILE = "/run/secrets/edge_board_secret"; // compose secret edge_board_secret, read per request
export const LINK_TTL_HOURS = 24; // setup, invite and reset links in public mode (design decision D9)
const fail = (m) => { throw new Error(m); };

/** Why `ip` can't be the front door's address (null when it can): a dotted-quad IPv4 that is publicly routable. */
export function publicIPv4Problem(ip) {
  const o = String(ip ?? "").split(".");
  if (o.length !== 4 || o.some((x) => !/^(0|[1-9]\d{0,2})$/.test(x) || Number(x) > 255)) return `${ip} is not an IPv4 address`;
  const [a, b] = o.map(Number);
  if (a === 10 || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168)) return `${ip} is a private address (RFC 1918): the host is behind NAT`;
  if (a === 100 && b >= 64 && b <= 127) return `${ip} is a carrier-grade NAT address (100.64.0.0/10)`;
  if (a === 127 || a === 0 || (a === 169 && b === 254) || a >= 224) return `${ip} is not a public unicast address`;
  return null;
}

/** The default route's source IPv4 on this host (`ip route get`), checked public; throws saying why not. */
export function detectPublicIPv4() {
  let route;
  try { route = execFileSync("ip", ["-4", "-j", "route", "get", "1.1.1.1"], { encoding: "utf8" }); } catch { fail("no IPv4 default route (ip route get 1.1.1.1 failed)"); }
  const ip = JSON.parse(route)[0]?.prefsrc;
  const problem = publicIPv4Problem(ip);
  if (problem) fail(`${problem}; set AIDENHQ_PUBLIC_IP in .env if the server has a public IPv4 that forwards 443 to it`);
  return ip;
}

/**
 * frontDoor(ip) → { caddyfile, compose, board }: the Caddyfile, the `caddy` service and the board's environment in public
 * mode. Only `set` for the headers Caddy owns (a delete of the same name in header_up runs after the set and removes it);
 * the deletes are for forwarding headers Caddy doesn't set, so the board only ever sees Caddy's.
 */
export function frontDoor(ip) {
  const problem = publicIPv4Problem(ip);
  if (problem) fail(`exposure public: AIDENHQ_PUBLIC_IP ${problem} (node scripts/front-door.mjs detect)`);
  const caddyfile = `# Generated by scripts/compile.mjs (scripts/front-door.mjs) for settings.exposure: public. Do not edit.
{
	admin off
	persist_config off
	# No listener on 80 (decision D1): no redirect server, and the certificate is validated over TLS-ALPN-01 on 443.
	auto_https disable_redirects
	servers {
		protocols h1 h2
		timeouts {
			read_header 10s
			read_body 60s
			idle 2m
		}
		max_header_size 64KB
	}
}
https://${ip} {
	# The site's own issuer, never Caddy's automatic choice, so its own CA's self-signed certificate is never served.
	tls {
		issuer acme {
			profile shortlived
			disable_http_challenge
		}
	}
	reverse_proxy ${BOARD_UPSTREAM} {
		header_up -Forwarded
		header_up -X-Real-IP
		header_up -X-Forwarded-Port
		header_up -X-Forwarded-Server
		header_up -X-Forwarded-Prefix
		header_up X-Forwarded-Proto https
		header_up X-AidenHQ-Client-IP {remote_host}
		header_up X-AidenHQ-Edge {file.${EDGE_SECRET_FILE}}
	}
	header {
		Strict-Transport-Security "max-age=86400"
		X-Content-Type-Options nosniff
		Referrer-Policy no-referrer
		-Server
		-Via
	}
}
`;
  const caddy = {
    build: "./services/caddy", image: "aidenhq/caddy:local", network_mode: "host", restart: "unless-stopped",
    user: "${PUID:-1000}:${PGID:-100}", read_only: true, security_opt: ["no-new-privileges:true"], cap_drop: ["ALL"], cap_add: ["NET_BIND_SERVICE"],
    // Caddy reads its config once (admin is off): the hash makes compose recreate it exactly when the Caddyfile changes.
    labels: { "aidenhq.caddyfile-sha256": createHash("sha256").update(caddyfile).digest("hex") },
    // Certificates and the ACME account, the only writable place (data/caddy, 0700, the owner's; compile makes it).
    volumes: ["./config/Caddyfile:/etc/caddy/Caddyfile:ro", "${AIDENHQ_DATA_DIR:-./data}/caddy:/data"],
    secrets: ["edge_board_secret"],
  };
  // The board answers to the IP over https, mints 24-hour links there, and warns the owner before the certificate lapses.
  const board = { environment: { BOARD_LAN_HOSTS: ip, BOARD_LAN_URL: `https://${ip}`, BOARD_LINK_TTL_HOURS: String(LINK_TTL_HOURS), BOARD_FRONT_DOOR: ip } };
  return { caddyfile, compose: { services: { caddy, board } } };
}

/** curl https://<ip>/healthz against the system trust store until it answers (any HTTP status) or `seconds` pass. */
export function waitForCertificate(ip, seconds = 180) {
  const until = Date.now() + seconds * 1000;
  for (;;) {
    const r = spawnSync("curl", ["-sS", "-o", "/dev/null", "-w", "%{http_code}", "--max-time", "10", `https://${ip}/healthz`], { encoding: "utf8" });
    if (r.status === 0 && /^[1-5]\d\d$/.test(r.stdout)) return true;
    if (Date.now() > until) return false;
    spawnSync("sleep", ["5"]);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, ip, s] = process.argv.slice(2);
  try {
    if (cmd === "detect") console.log(detectPublicIPv4());
    else if (cmd === "wait") {
      const problem = publicIPv4Problem(ip);
      if (problem) fail(problem);
      if (!waitForCertificate(ip, Number(s) || 180)) fail(`https://${ip} has no publicly trusted certificate yet`);
    } else fail("usage: front-door.mjs detect | wait <ip> [seconds]");
  } catch (e) {
    console.error(`front-door: ${e.message}`);
    process.exit(1);
  }
}
