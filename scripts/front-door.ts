// The public HTTPS front door (settings.exposure: public; docs/design/access.md, Exposure modes): Caddy on the host
// network with a Let's Encrypt certificate for the server's public IPv4 (the `shortlived` profile, TLS-ALPN-01 only: port
// 80 stays closed). Two sites on that one name, the same layout as `tailscale serve`:
//   https://<ip>       → the board (127.0.0.1:3121)
//   https://<ip>:8446  → the kernel's admin listener (127.0.0.1:3120): sign-in, links, approvals. Its own origin, as the
//                        kernel's forms require; Caddy names the client there (X-AidenHQ-Client-IP) beside the edge secret.
//   https://<ip>:8447  → the gate (127.0.0.1:3130): the module door (docs/design/app-doors.md), e.g. the self-hosted Primer.
//   https://<app>.<ip-with-dashes>.sslip.io → the gate (127.0.0.1:3130), with an app door (docs/design/app-doors.md): one
//                        certificate per name, ordered on demand only for a name the gate's door-ask approves.
// The IP comes from the host's .env (AIDENHQ_PUBLIC_IP, which ops/setup.sh writes), never from instance.yaml: agents can
// edit that through an apply. Compile (scripts/compile.ts) writes config/Caddyfile and the `caddy` service from it.
//   node scripts/front-door.ts detect                  the default route's public IPv4, or exit 1 saying why there is none
//   node scripts/front-door.ts wait <ip> [seconds]     wait (default 180) until both sites answer over a publicly trusted
//                                                       certificate (Node's root store); exit 1 if they never do
//   node scripts/front-door.ts caddyfile <ip> [<acme directory>]
//                                                       print the Caddyfile (a directory: ops/test/caddy-staging-issuance.sh)
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { DOOR_PORT } from "./edge.ts";
import { LOG_ROTATION } from "./compiler/services.ts";

export const ADMIN_PORT = 8446;
const GATE_PORT = 3130; // scripts/edge.ts GATE_PORT: the gate on the host's loopback // the admin listener's public port (tailscale serve uses the same one)
export const EDGE_SECRET_FILE = "/run/secrets/edge_board_secret"; // compose secret edge_board_secret, read per request
const fail = (m: string): never => { throw new Error(m); };

/** Why `ip` can't be the front door's address (null when it can): a dotted-quad IPv4 that is publicly routable. */
export function publicIPv4Problem(ip: unknown) {
  const o = String(ip ?? "").split(".");
  if (o.length !== 4 || o.some((x) => !/^(0|[1-9]\d{0,2})$/.test(x) || Number(x) > 255)) return `${ip} is not an IPv4 address`;
  const [a, b] = o.map(Number) as [number, number];
  if (a === 10 || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168)) return `${ip} is a private address (RFC 1918): the host is behind NAT`;
  if (a === 100 && b >= 64 && b <= 127) return `${ip} is a carrier-grade NAT address (100.64.0.0/10)`;
  if (a === 127 || a === 0 || (a === 169 && b === 254) || a >= 224) return `${ip} is not a public unicast address`;
  return null;
}

/** The board's and the admin listener's public URLs for `ip` (ops/setup.sh writes them into .env, where the kernel reads them). */
export const publicUrls = (ip: string | undefined) => ({ board: `https://${ip}`, admin: `https://${ip}:${ADMIN_PORT}` });

/** The default route's source IPv4 on this host (`ip route get`), checked public; throws saying why not. */
export function detectPublicIPv4() {
  let route!: string;
  try { route = execFileSync("ip", ["-4", "-j", "route", "get", "1.1.1.1"], { encoding: "utf8" }); } catch { fail("no IPv4 default route (ip route get 1.1.1.1 failed)"); }
  const ip = JSON.parse(route)[0]?.prefsrc;
  const problem = publicIPv4Problem(ip);
  if (problem) fail(`${problem}; set AIDENHQ_PUBLIC_IP in .env if the server has a public IPv4 that forwards 443 and ${ADMIN_PORT} to it`);
  return ip;
}

/**
 * The Caddyfile for `ip` (and, with `doorBase`, the gate's app doors under it). Only `set` for the headers Caddy owns: a header_up delete of a name it also sets runs after the
 * set and removes it. The deletes are for forwarding headers Caddy doesn't set, so the listeners only see Caddy's own.
 * `directory`: another ACME directory (Let's Encrypt staging, for the exit check); unset is Let's Encrypt production.
 */
export function caddyfile(ip: string | undefined, directory?: string, doorBase?: string) {
  const problem = publicIPv4Problem(ip);
  if (problem) fail(problem);
  const site = (port: number, upstream: string, edge: boolean) => `https://${ip}${port ? `:${port}` : ""} {
	import ip_cert
	reverse_proxy ${upstream} {
		import strip
${edge ? `		header_up X-AidenHQ-Client-IP {remote_host}
		header_up X-AidenHQ-Edge {file.${EDGE_SECRET_FILE}}
` : `		header_up -X-AidenHQ-Client-IP
		header_up -X-AidenHQ-Edge
`}	}
	import response
}
`;
  return `# Generated by scripts/compile.ts (scripts/front-door.ts) for settings.exposure: public. Do not edit.
{
	admin off
	persist_config off
	# No listener on 80 (decision D1): no redirect server; the certificate is validated over TLS-ALPN-01 on 443.
	auto_https disable_redirects
	# Browsers send no SNI for an IP, and behind 1:1 NAT the connection's own address isn't the certificate's: name it.
	default_sni ${ip}
	servers {
		protocols h1 h2
		timeouts {
			read_header 10s
			read_body 60s
			idle 2m
		}
		max_header_size 64KB
	}
${doorBase ? `	# App doors: a certificate is ordered at a name's first handshake, only if the gate serves an app there.
	on_demand_tls {
		ask http://127.0.0.1:${GATE_PORT}/.aidenhq/door-ask
	}
` : ""}}
# Each site names its issuer: Caddy's automatic choice for an IP can be its own local CA, whose certificate is never served.
(ip_cert) {
	tls {
		issuer acme {
${directory ? `			dir ${directory}\n` : ""}			profile shortlived
			disable_http_challenge
		}
	}
}
(strip) {
	header_up -Forwarded
	header_up -X-Real-IP
	header_up -X-Forwarded-Port
	header_up -X-Forwarded-Server
	header_up -X-Forwarded-Prefix
	header_up -Tailscale-User-Login
	header_up -Tailscale-User-Name
	header_up -Tailscale-User-Profile-Pic
	header_up X-Forwarded-Proto https
}
(response) {
	header {
		Strict-Transport-Security "max-age=86400"
		X-Content-Type-Options nosniff
		Referrer-Policy no-referrer
		-Server
		-Via
	}
}
${site(0, "127.0.0.1:3121", false)}${site(ADMIN_PORT, "127.0.0.1:3120", true)}${site(DOOR_PORT, `127.0.0.1:${GATE_PORT}`, false)}${doorBase ? `# App doors: each one name under ${doorBase} (one label), its own certificate, then the gate. No sign-in passes here.
https://*.${doorBase} {
	tls {
		on_demand
		issuer acme {
${directory ? `			dir ${directory}\n` : ""}			disable_http_challenge
		}
	}
	reverse_proxy 127.0.0.1:${GATE_PORT} {
		import strip
		header_up -X-AidenHQ-Client-IP
		header_up -X-AidenHQ-Edge
	}
	import response
}
` : ""}`;
}

/** Whether https://<ip> and https://<ip>:8446 both answer (any status) over a verified certificate within `seconds`. */
export async function waitForCertificate(ip: string | undefined, seconds = 180) {
  const until = Date.now() + seconds * 1000;
  const up = (url: string) => fetch(url, { redirect: "manual", signal: AbortSignal.timeout(10_000) }).then(() => true, () => false);
  for (;;) {
    if ((await up(`https://${ip}/`)) && (await up(`https://${ip}:${ADMIN_PORT}/`))) return true;
    if (Date.now() > until) return false;
    await new Promise((r) => setTimeout(r, 5000));
  }
}

/** The `caddy` compose service for a Caddyfile (compile writes the file to config/Caddyfile). */
export function caddyService(file: string) {
  return {
    build: "./services/caddy", image: "aidenhq/caddy:local", network_mode: "host", restart: "unless-stopped", logging: LOG_ROTATION,
    user: "${PUID:-1000}:${PGID:-100}", read_only: true, security_opt: ["no-new-privileges:true"], cap_drop: ["ALL"], cap_add: ["NET_BIND_SERVICE"],
    // Caddy reads its config once (admin is off): the hash makes compose recreate it exactly when the Caddyfile changes.
    labels: { "aidenhq.caddyfile-sha256": createHash("sha256").update(file).digest("hex") },
    // Certificates and the ACME account, the only writable place (data/caddy, 0700, the owner's; compile makes it).
    volumes: ["./config/Caddyfile:/etc/caddy/Caddyfile:ro", "${AIDENHQ_DATA_DIR:-./data}/caddy:/data"],
    secrets: ["edge_board_secret"],
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, ip, dir] = process.argv.slice(2);
  try {
    if (cmd === "detect") console.log(detectPublicIPv4());
    else if (cmd === "caddyfile") process.stdout.write(caddyfile(ip, dir));
    else if (cmd === "wait") {
      const problem = publicIPv4Problem(ip);
      if (problem) fail(problem);
      if (!(await waitForCertificate(ip, Number(dir) || 180))) fail(`https://${ip} has no publicly trusted certificate yet`);
    } else fail("usage: front-door.ts detect | wait <ip> [seconds] | caddyfile <ip> [<acme directory>]");
  } catch (e) {
    console.error(`front-door: ${(e as Error).message}`);
    process.exit(1);
  }
}
