import { test } from "node:test";
import assert from "node:assert/strict";
import { discover } from "../service/src/discover.ts";

test("discover: generated paths from .gitattributes, lockfiles and headers; the generator from a CI job, else the build files", () => {
  const d = discover({
    ".gitattributes": "# generated\ngen/** linguist-generated\ndocs/** linguist-documentation\n",
    ".github/workflows/ci.yml": [
      "name: ci",
      "on: [pull_request]",
      "jobs:",
      "  test:",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - run: npm test",
      "  gen:",
      "    name: generated code up to date",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - uses: actions/checkout@v4",
      "      - run: |",
      "          make generate",
      "          git diff --exit-code",
    ].join("\n"),
    "Makefile": "generate:\n\tgo run ./cmd/gen\n",
    "web/package.json": JSON.stringify({ scripts: { generate: "openapi-ts" } }),
    "api/types.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
  });
  assert.ok(d.globs.includes("gen/**"));
  assert.ok(!d.globs.some((g) => g.startsWith("docs")));
  assert.ok(d.globs.includes("**/package-lock.json"));
  assert.ok(d.globs.includes("api/types.pb.go"));
  assert.deepEqual(d.commands, [{ dir: ".", cmd: "make generate" }, { dir: "web", cmd: "npm run generate" }]);
  assert.deepEqual(d.ambiguous, []);
  // A step's own working directory is the generator's, whatever the job's later steps say.
  const api = discover({ ".github/workflows/gen.yml": ["jobs:", "  codegen:", "    runs-on: ubuntu-latest", "    steps:", "      - run: make generate", "        working-directory: api", "      - run: git diff --exit-code", "        working-directory: web"].join("\n") });
  assert.deepEqual(api.commands, [{ dir: "api", cmd: "make generate" }]);
});
