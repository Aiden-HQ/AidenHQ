import { test } from "node:test";
import assert from "node:assert/strict";
import { discover } from "../service/src/discover.ts";

test("discover: generated paths from .gitattributes and lockfiles only; the generator from a CI job, else the build files", () => {
  const d = discover({
    ".gitattributes": "# generated\ngen/** linguist-generated\ndocs/** linguist-documentation\n",
    ".github/workflows/ci.yml": [
      "name: ci",
      "on: [pull_request]",
      "jobs:",
      "  test:",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - run: npm test",
      "  gen:",
      "    name: generated code up to date",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - uses: actions/checkout@v4",
      "      - run: |",
      "          make generate",
      "          git diff --exit-code",
    ].join("\n"),
    "Makefile": "generate:\n\tgo run ./cmd/gen\n",
    "web/package.json": JSON.stringify({ scripts: { generate: "openapi-ts" } }),
    "api/types.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
  });
  assert.ok(d.globs.includes("gen/**"));
  assert.ok(!d.globs.some((g) => g.startsWith("docs")));
  assert.ok(d.globs.includes("**/package-lock.json"));
  assert.ok(!d.globs.includes("api/types.pb.go"), "a header the repo didn't declare in .gitattributes widens nothing");
  assert.deepEqual(d.commands, [{ dir: ".", cmd: "make generate" }, { dir: "web", cmd: "npm run generate" }]);
  assert.deepEqual(d.ambiguous, []);
  // A step's own working directory is the generator's, whatever the job's later steps say.
  const api = discover({ ".github/workflows/gen.yml": ["jobs:", "  codegen:", "    runs-on: ubuntu-latest", "    steps:", "      - run: make generate", "        working-directory: api", "      - run: git diff --exit-code", "        working-directory: web"].join("\n") });
  assert.deepEqual(api.commands, [{ dir: "api", cmd: "make generate" }]);
  // A `needs:` list is no step: the job's later defaults.run.working-directory is the job's own.
  const needs = discover({ ".github/workflows/gen.yml": ["jobs:", "  codegen:", "    needs:", "      - build", "      - lint", "    defaults:", "      run:", "        working-directory: api", "    steps:", "      - run: make generate"].join("\n") });
  assert.deepEqual(needs.commands, [{ dir: "api", cmd: "make generate" }]);
});

test("discover: more generated files than the repair request holds are capped and said, lockfiles kept", () => {
  const files: Record<string, string> = {};
  // Discovery takes only the repo's own `linguist-generated` paths (and lockfiles): 300 of them.
  files[".gitattributes"] = Array.from({ length: 300 }, (_, i) => `gen/f${i}.pb.go linguist-generated`).join("\n");
  const d = discover(files);
  assert.equal(d.globs.length, 200);
  assert.ok(d.globs.includes("**/package-lock.json"));
  assert.ok(d.ambiguous.some((a) => /left out of the repair/.test(a)));
});
