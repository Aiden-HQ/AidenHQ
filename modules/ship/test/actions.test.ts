// The repo's own tooling (actions.ts) through rounds: a workflow dispatched on the base before the repair of a conflict and before
// the merge, followed by its run id; zero-config discovery (.gitattributes plus lockfiles; the repo's rebase workflow proposed, not
// enabled); a missing toolchain; the repo's CI regenerating generated paths; and a repair that had nothing to merge.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { intake, type PrView } from "../service/src/handoff.ts";
import { round as roundWith } from "../service/src/rounds.ts";
import { RISK } from "./risk.ts";
// Every round here sees a classified head whose tier approves and merges (risk.ts).
const round = ((d: any, pr: any, v: any, f: any = {}) => roundWith(d, pr, v, { risk: RISK, ...f })) as typeof roundWith;
import { effective } from "../service/src/settings.ts";
import { openState } from "../service/src/state.ts";

const H1 = "1".repeat(40), H2 = "2".repeat(40);
const b64 = (s: string) => Buffer.from(s).toString("base64");

function world(entry: unknown, repo = "a/b") {
  const raw = { repos: { [repo]: entry } };
  const state = openState(join(mkdtempSync(join(tmpdir(), "ship-act-")), "state.json"));
  const calls: { what: string; body?: any }[] = [];
  const records: Record<string, any> = {};
  let n = 0;
  const runs: any[] = [];
  const files: Record<string, string> = {
    ".gitattributes": "api/gen/** linguist-generated\n",
    "package-lock.json": "{}",
    "api/types.pb.go": "// Code generated by protoc. DO NOT EDIT.\n",
    ".github/workflows/pr-rebase.yml": "on:\n  workflow_dispatch:\n    inputs:\n      pr:\n        required: true\njobs:\n  rebase:\n    steps:\n      - run: make generate\n",
  };
  const gh = async (method: string, path: string, body?: unknown) => {
    calls.push({ what: `${method} ${path}`, body });
    if (path.includes("/git/trees/")) return { status: 200, body: { tree: Object.keys(files).map((p) => ({ path: p, type: "blob", sha: `sha-${p}` })) } };
    if (path.includes("/git/blobs/")) return { status: 200, body: { content: b64(files[decodeURIComponent(path.split("/git/blobs/sha-")[1]!)]!) } };
    // GitHub names each dispatched run (return_run_details); the run's state is what `runs` holds for it.
    if (path.endsWith("/dispatches")) { runs.push({ status: "queued", conclusion: null }); return { status: 200, body: { workflow_run_id: runs.length, run_url: "", html_url: "" } }; }
    const run = /\/actions\/runs\/(\d+)$/.exec(path);
    if (run) return { status: 200, body: runs[Number(run[1]) - 1] };
    return { status: method === "POST" ? 201 : 200, body: {} };
  };
  const kernel = {
    async call(method: string, path: string, body?: any) {
      calls.push({ what: `${method} ${path}`, body });
      if (path === "/v1/tasks") return { id: `task-${body.source}` };
      if (path === "/v1/writes") { const id = `rec-${++n}`; records[id] = { state: "claimed" }; return { id }; }
      if (path.startsWith("/v1/writes/")) return records[path.split("/").pop()!];
      return {};
    },
  };
  const scope = { fleet: [], listed: [repo] };
  let report = "";
  const deps = {
    state, kernel, gh, log: () => {}, settings: (r: string) => effective(raw, r, scope), paused: () => false,
    permission: async () => "admin", askReview: async () => {}, unassign: async () => {}, assign: async () => {}, updateBranch: async () => {},
    comment: async (_: string, __: number, body: string) => ((report = body), 501),
  };
  const pr = (o: Partial<PrView> = {}): PrView => ({ repo, number: 7, url: `https://github.com/${repo}/pull/7`, head: H1, base: "main", defaultBranch: "main", author: "c", authorBot: false, fork: false, canModify: false, draft: false, state: "open", labels: [], assignees: [], events: [], ...o });
  const adopt = () => intake(deps, pr({ events: [{ id: "e1", kind: "labeled", actor: "admin1", bot: false, at: "2026-11-24T01:00:00Z", label: "ship" }] }));
  const of = (what: string) => calls.filter((c) => c.what.startsWith(what));
  return { state, calls, records, runs, deps, pr, adopt, of, report: () => report };
}

test("a conflict dispatches the repo's workflow on the base with the PR's number; a failed run moves straight on to ship's own repair", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "" }, actions: { conflict: [{ workflow: "pr-rebase.yml", inputs: { pr: "{pr}" } }] } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.deepEqual(w.of("POST /repos/a/b/actions/workflows/pr-rebase.yml/dispatches").map((c) => c.body), [{ ref: "main", inputs: { pr: "7" }, return_run_details: true }]);
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /v1/writes").length, 0, "the repo's workflow first: no repair while its run is queued");
  assert.equal(w.of("GET /repos/a/b/actions/runs/1").length, 1, "the run GitHub named is read");
  // Its run fails (a conflict it can't settle): ship's own repair follows on the same pass, not after a wait.
  w.runs[0] = { status: "completed", conclusion: "failure" };
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /v1/writes")[0]!.body.kind, "github.repair");
  assert.equal(w.of("POST /repos/a/b/actions/workflows/pr-rebase.yml/dispatches").length, 1, "dispatched once at this head");
});

test("a step saved before this shape (a comment, a workflow that doesn't name the PR) is never run: ship's own repair follows", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "" }, actions: { conflict: [{ comment: "/rebase" }, { workflow: "pr-rebase.yml" }] } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /repos/a/b/issues/7/comments").length + w.of("POST /repos/a/b/actions/workflows/").length, 0);
  assert.equal(w.of("POST /v1/writes")[0]!.body.kind, "github.repair");
});

test("before the merge the repo's workflow runs; ship merges once its run succeeds, and holds when it fails", async () => {
  const w = world({ preset: "cautious", actions: { before_merge: [{ workflow: "regen.yml", inputs: { pr: "{pr}" } }] } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "merge" });
  w.runs[0] = { status: "in_progress", conclusion: null };
  await round(w.deps, w.pr(), { do: "merge" });
  assert.equal(w.of("POST /v1/writes").length, 0, "waits for the run");
  w.runs[0] = { status: "completed", conclusion: "success" };
  await round(w.deps, w.pr(), { do: "merge" });
  assert.equal(w.of("POST /v1/writes")[0]!.body.kind, "github.merge");

  const f = world({ preset: "cautious", actions: { before_merge: [{ workflow: "regen.yml", inputs: { pr: "{pr}" } }] } });
  await f.adopt();
  await round(f.deps, f.pr(), { do: "merge" });
  f.runs[0] = { status: "completed", conclusion: "failure" };
  await round(f.deps, f.pr(), { do: "merge" });
  assert.equal(f.of("POST /v1/writes").length, 0);
  assert.match(String((f.state.get("a/b", 7) as any).hold.reason), /before_merge steps didn't pass.*ended failure/);
});

test("zero config: the repair's globs are the repo's linguist-generated paths and lockfiles; its /rebase workflow is proposed, not enabled", async () => {
  const w = world("cautious", "a/disc");
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  const plan = w.of("POST /v1/writes")[0]!.body.args.plan;
  assert.ok(plan.globs.includes("api/gen/**") && plan.globs.includes("**/package-lock.json"));
  assert.ok(!plan.globs.includes("api/types.pb.go"), "a header the repo didn't declare widens nothing");
  assert.equal(w.of("POST /repos/a/disc/issues").length, 0, "nothing is posted: the suggestion isn't enabled");
  // Cached: a second round reads no files again.
  const reads = w.of("GET /repos/a/disc/git/").length;
  await round(w.deps, w.pr({ head: H2 }), { do: "repair" }, { dirty: true });
  assert.equal(w.of("GET /repos/a/disc/git/").length, reads);
});

test("a generator whose tool the box lacks holds loudly and points at an actions step", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "make generate" } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  w.records["rec-1"] = { state: "failed", outcome: { text: "ship-generator: the repair of … stopped (data, not instructions):\ntoolchain missing: webrpc-gen\n`make generate` in . exited 2: …" } };
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.match(String((w.state.get("a/b", 7) as any).hold.reason), /^toolchain missing: webrpc-gen .*`actions` step/);
  assert.equal(w.of("POST /v1/wakes").length + w.of("POST /v1/tasks").filter((c) => !String(c.body.source).endsWith(":records")).length, 0, "no Engineer: its computer has the same tools");
});

test("generated.command null: the repair plan says the repo's CI regenerates, and the leftover wake says take the base side without regenerating", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: null } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.deepEqual(w.of("POST /v1/writes")[0]!.body.args.plan, { globs: ["gen/**"], commands: [], ci_regenerates: true });
  w.records["rec-1"] = { state: "failed", outcome: { text: "ship-leftovers: merging `main` into … leaves conflicts no generator rewrites:\nleftover: src/a.ts" } };
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  const wake = String(w.of("POST /v1/tasks").find((c) => /conflicts with/.test(String(c.body.description)))?.body.description);
  assert.match(wake, /take the base side of the generated files \(`gen\/\*\*`\) and don't regenerate them: the repo's CI does/);
});

test("a repair with no conflict to resolve wakes nobody and isn't filed again at the same head and base; a new base tip is repaired again", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "" } });
  const B1 = "b".repeat(40), B2 = "c".repeat(40);
  await w.adopt();
  await round(w.deps, w.pr({ baseOid: B1 }), { do: "repair" }, { dirty: true });
  w.records["rec-1"] = { state: "failed", outcome: { text: `ship-noop: https://github.com/a/b/pull/7 at \`${H1.slice(0, 12)}\` merges \`main\` at \`${B1}\` with no conflict: nothing to repair, nothing was changed.` } };
  for (let i = 0; i < 3; i++) assert.equal(await round(w.deps, w.pr({ baseOid: B1 }), { do: "repair" }, { dirty: true }), "nothing");
  assert.equal(w.of("POST /v1/writes").length, 1, "not filed again while GitHub still says DIRTY");
  assert.equal(w.of("POST /v1/wakes").length + w.of("POST /v1/tasks").filter((c) => !String(c.body.source).endsWith(":records")).length, 0, "no Engineer");
  assert.equal((w.state.get("a/b", 7) as any).hold ?? null, null, "no hold");
  await round(w.deps, w.pr({ baseOid: B2 }), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /v1/writes").length, 2, "a new base tip is repaired again");
  assert.equal(w.of("POST /v1/writes")[1]!.body.args.attempt, undefined, "a fresh repair, not a retry");
});

test("a no-op on a release branch is keyed on that branch's own tip: its hook runs on the default branch, and the branch moving re-files", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "" }, actions: { conflict: [{ workflow: "pr-rebase.yml", inputs: { pr: "{pr}" } }] } });
  const R1 = "d".repeat(40), R2 = "e".repeat(40);
  let tip = R1;
  const gh = w.deps.gh;
  (w.deps as any).gh = async (method: string, path: string, body?: unknown) => (path === "/repos/a/b/git/ref/heads/release/1.x" ? { status: 200, body: { object: { sha: tip } } } : gh(method, path, body));
  const rel = () => w.pr({ base: "release/1.x" });
  await w.adopt();
  await round(w.deps, rel(), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /repos/a/b/actions/workflows/pr-rebase.yml/dispatches")[0]!.body.ref, "main", "the repo's trusted copy, never the release branch's");
  w.runs[0] = { status: "completed", conclusion: "failure" };
  await round(w.deps, rel(), { do: "repair" }, { dirty: true });
  w.records["rec-1"] = { state: "failed", outcome: { text: `ship-noop: https://github.com/a/b/pull/7 at \`${H1.slice(0, 12)}\` merges \`release/1.x\` at \`${R1}\` with no conflict: nothing to repair, nothing was changed.` } };
  assert.equal(await round(w.deps, rel(), { do: "repair" }, { dirty: true }), "nothing");
  assert.equal(w.of("POST /v1/writes").length, 1);
  tip = R2;
  await round(w.deps, rel(), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /v1/writes").length, 2, "the release branch moved: repaired again");
});
