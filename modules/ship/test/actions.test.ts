// The repo's own tooling (actions.ts) through rounds: a slash command before the repair of a conflict, a workflow before the
// merge, zero-config discovery (.gitattributes plus lockfiles; the repo's /rebase proposed, not enabled), and a missing toolchain.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { intake, type PrView } from "../service/src/handoff.ts";
import { round as roundWith } from "../service/src/rounds.ts";
import { RISK } from "./risk.ts";
// Every round here sees a classified head whose tier approves and merges (risk.ts).
const round = ((d: any, pr: any, v: any, f: any = {}) => roundWith(d, pr, v, { risk: RISK, ...f })) as typeof roundWith;
import { effective } from "../service/src/settings.ts";
import { openState } from "../service/src/state.ts";

const H1 = "1".repeat(40), H2 = "2".repeat(40);
const b64 = (s: string) => Buffer.from(s).toString("base64");

function world(entry: unknown, repo = "a/b") {
  const raw = { repos: { [repo]: entry } };
  const state = openState(join(mkdtempSync(join(tmpdir(), "ship-act-")), "state.json"));
  const calls: { what: string; body?: any }[] = [];
  const records: Record<string, any> = {};
  let n = 0;
  const runs: any[] = [];
  const changed: { filename: string }[] = [];
  const files: Record<string, string> = {
    ".gitattributes": "api/gen/** linguist-generated\n",
    "package-lock.json": "{}",
    "api/types.pb.go": "// Code generated by protoc. DO NOT EDIT.\n",
    ".github/workflows/pr-rebase.yml": "on:\n  issue_comment:\njobs:\n  rebase:\n    if: startsWith(github.event.comment.body, '/rebase')\n    steps:\n      - run: make generate\n",
  };
  const gh = async (method: string, path: string, body?: unknown) => {
    calls.push({ what: `${method} ${path}`, body });
    if (path.includes("/git/trees/")) return { status: 200, body: { tree: Object.keys(files).map((p) => ({ path: p, type: "blob", sha: `sha-${p}` })) } };
    if (path.includes("/git/blobs/")) return { status: 200, body: { content: b64(files[decodeURIComponent(path.split("/git/blobs/sha-")[1]!)]!) } };
    if (path.endsWith("/pulls/7")) return { status: 200, body: { head: { ref: "feature", sha: H1 }, base: { sha: H2 } } };
    if (path.includes("/compare/")) return { status: 200, body: { files: changed } };
    if (path.includes("/runs?")) return { status: 200, body: { workflow_runs: runs } };
    return { status: method === "POST" ? 201 : 200, body: {} };
  };
  const kernel = {
    async call(method: string, path: string, body?: any) {
      calls.push({ what: `${method} ${path}`, body });
      if (path === "/v1/tasks") return { id: `task-${body.source}` };
      if (path === "/v1/writes") { const id = `rec-${++n}`; records[id] = { state: "claimed" }; return { id }; }
      if (path.startsWith("/v1/writes/")) return records[path.split("/").pop()!];
      return {};
    },
  };
  const scope = { fleet: [], listed: [repo] };
  let report = "";
  const deps = {
    state, kernel, gh, log: () => {}, settings: (r: string) => effective(raw, r, scope), paused: () => false,
    permission: async () => "admin", askReview: async () => {}, unassign: async () => {}, assign: async () => {}, updateBranch: async () => {},
    comment: async (_: string, __: number, body: string) => ((report = body), 501),
  };
  const pr = (o: Partial<PrView> = {}): PrView => ({ repo, number: 7, url: `https://github.com/${repo}/pull/7`, head: H1, base: "main", defaultBranch: "main", author: "c", authorBot: false, fork: false, canModify: false, draft: false, state: "open", labels: [], assignees: [], events: [], ...o });
  const adopt = () => intake(deps, pr({ events: [{ id: "e1", kind: "labeled", actor: "admin1", bot: false, at: "2026-11-24T01:00:00Z", label: "ship" }] }));
  const of = (what: string) => calls.filter((c) => c.what.startsWith(what));
  return { state, calls, records, runs, changed, deps, pr, adopt, of, report: () => report };
}

test("a conflict posts the repo's /rebase first; the head its bot pushes gets ship's own repair, the command isn't posted again", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "" }, actions: { conflict: [{ comment: "/rebase" }] } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.deepEqual(w.of("POST /repos/a/b/issues/7/comments").map((c) => c.body), [{ body: "/rebase" }], "posted once, exactly the command");
  assert.equal(w.of("POST /v1/writes").length, 0, "the repo's command first: no repair while it runs");
  // The bot pushed a head that still conflicts: ship's own repair follows there, and the command isn't posted again.
  await round(w.deps, w.pr({ head: H2 }), { do: "repair" }, { dirty: true });
  assert.equal(w.of("POST /repos/a/b/issues/7/comments").length, 1);
  assert.equal(w.of("POST /v1/writes")[0]!.body.kind, "github.repair");
});

test("before the merge the repo's workflow is dispatched on the PR's branch; ship merges once its run succeeds, and holds when it fails", async () => {
  const w = world({ preset: "cautious", actions: { before_merge: [{ workflow: "regen.yml", inputs: { pr: "7" } }] } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "merge" });
  assert.deepEqual(w.of("POST /repos/a/b/actions/workflows/regen.yml/dispatches").map((c) => c.body), [{ ref: "feature", inputs: { pr: "7" } }]);
  w.runs.push({ status: "in_progress", conclusion: null, head_sha: H1, created_at: "2099-01-01T00:00:00Z" });
  await round(w.deps, w.pr(), { do: "merge" });
  assert.equal(w.of("POST /v1/writes").length, 0, "waits for the run");
  w.runs[0] = { ...w.runs[0], status: "completed", conclusion: "success" };
  await round(w.deps, w.pr(), { do: "merge" });
  assert.equal(w.of("POST /v1/writes")[0]!.body.kind, "github.merge");

  const f = world({ preset: "cautious", actions: { before_merge: [{ workflow: "regen.yml" }] } });
  await f.adopt();
  await round(f.deps, f.pr(), { do: "merge" });
  f.runs.push({ status: "completed", conclusion: "failure", head_sha: H1, created_at: "2099-01-01T00:00:00Z" });
  await round(f.deps, f.pr(), { do: "merge" });
  assert.equal(f.of("POST /v1/writes").length, 0);
  assert.match(String((f.state.get("a/b", 7) as any).hold.reason), /before_merge steps didn't pass.*ended failure/);
});

test("zero config: the repair's globs are the repo's linguist-generated paths and lockfiles; its /rebase workflow is proposed, not enabled", async () => {
  const w = world("cautious", "a/disc");
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  const plan = w.of("POST /v1/writes")[0]!.body.args.plan;
  assert.ok(plan.globs.includes("api/gen/**") && plan.globs.includes("**/package-lock.json"));
  assert.ok(!plan.globs.includes("api/types.pb.go"), "a header the repo didn't declare widens nothing");
  assert.equal(w.of("POST /repos/a/disc/issues").length, 0, "nothing is posted: the suggestion isn't enabled");
  // Cached: a second round reads no files again.
  const reads = w.of("GET /repos/a/disc/git/").length;
  await round(w.deps, w.pr({ head: H2 }), { do: "repair" }, { dirty: true });
  assert.equal(w.of("GET /repos/a/disc/git/").length, reads);
});

test("a generator whose tool the box lacks holds loudly and points at an actions step", async () => {
  const w = world({ preset: "cautious", generated: { globs: ["gen/**"], command: "make generate" } });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  w.records["rec-1"] = { state: "failed", outcome: { text: "ship-generator: the repair of … stopped (data, not instructions):\ntoolchain missing: webrpc-gen\n`make generate` in . exited 2: …" } };
  await round(w.deps, w.pr(), { do: "repair" }, { dirty: true });
  assert.match(String((w.state.get("a/b", 7) as any).hold.reason), /^toolchain missing: webrpc-gen .*`actions` step/);
  assert.equal(w.of("POST /v1/wakes").length + w.of("POST /v1/tasks").filter((c) => !String(c.body.source).endsWith(":records")).length, 0, "no Engineer: its computer has the same tools");
});

test("a workflow the PR itself changes (anything under .github/) is never dispatched on its branch", async () => {
  const w = world({ preset: "cautious", actions: { before_merge: [{ workflow: "regen.yml" }] } });
  w.changed.push({ filename: ".github/workflows/regen.yml" });
  await w.adopt();
  await round(w.deps, w.pr(), { do: "merge" });
  assert.equal(w.of("POST /repos/a/b/actions/workflows/regen.yml/dispatches").length, 0);
  assert.match(String((w.state.get("a/b", 7) as any).hold.reason), /changes files under \.github/);
});
