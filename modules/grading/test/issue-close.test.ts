// A closed issue counts as resolved when GitHub's own closer is a merged PR (in any repo), or a comment by an owner, member or
// collaborator carries the one line `Fixed by <owner>/<repo>#<n> (merge <sha>)` for a PR the code host reads as merged at that sha.
// Nothing else is scanned: other links never count and never mask the line.
import { test } from "node:test";
import assert from "node:assert/strict";
import { issueEvidence } from "../service/src/grader/evidence.ts";

const SHA = "b".repeat(40);
const base = { number: 7, state: "CLOSED", stateReason: "COMPLETED", closedAt: "2026-11-19T10:05:00Z", labels: { nodes: [] }, closedEvents: { nodes: [{ actor: { login: "someone" }, closer: null }] } };
const merged = { state: "MERGED", mergedAt: "2026-11-19T10:00:00Z", mergeCommit: { oid: SHA }, headRefOid: "a".repeat(40) };
const run = (issue: object, pr: (n: number) => object = () => merged) => issueEvidence("acme/app#7", { issue: async () => ({ repository: { issue: { ...base, ...issue } } }), pr: async (_r: string, n: number) => ({ repository: { pullRequest: pr(n) } }) });
const text = (e: { facts: string[] }) => e.facts.join("\n");
const said = (body: string, assoc = "OWNER", at = "2026-11-19T11:00:00Z") => ({ author: { login: "aiden" }, authorAssociation: assoc, createdAt: at, body });
const line = (n = 9, sha = SHA) => `Fixed by acme/app#${n} (merge ${sha})`;

test("a merged PR GitHub records as the closer counts, in this repo or another", async () => {
  for (const repo of ["acme/app", "acme/other"]) {
    const e = await run({ closedEvents: { nodes: [{ actor: { login: "github-actions" }, closer: { __typename: "PullRequest", number: 3, state: "MERGED", mergeCommit: { oid: "c".repeat(40) }, repository: { nameWithOwner: repo } } }] }, comments: { nodes: [] } });
    assert.match(text(e), new RegExp(`closing keyword of https://github.com/${repo}/pull/3.*merged`));
    assert.doesNotMatch(text(e), /does not count/);
  }
});

test("the Fixed-by line counts from an owner at any time, once the PR is merged at that sha", async () => {
  const e = await run({ comments: { nodes: [said(`Verified.\n\n${line()}\n\n🤖 Generated by Aiden`)] } });
  assert.match(text(e), /acme\/app\/pull\/9 merged at b{40}: merged at 2026-11-19T10:00:00Z/);
  assert.doesNotMatch(text(e), /does not count/);
  assert.match(e.version, /:b{12}\+/);
  // A PR merged at another sha, or not merged, is no resolution.
  assert.match(text(await run({ comments: { nodes: [said(line(9, "d".repeat(40)))] } })), /not that sha/);
  assert.match(text(await run({ comments: { nodes: [said(line())] } }, () => ({ state: "OPEN" }))), /open, not merged/);
});

test("an unrelated link beside a valid line, or five lines with the valid one last, never masks it", async () => {
  const unrelated = await run({ comments: { nodes: [said("Related: https://github.com/acme/app/pull/4"), said(`See acme/app#5.\n${line()}`)] } }, (n) => (n === 9 ? merged : { state: "OPEN" }));
  assert.match(text(unrelated), /pull\/9 merged at b{40}: merged at/);
  assert.doesNotMatch(text(unrelated), /pull\/[45]/);
  const five = await run({ comments: { nodes: [1, 2, 3, 4, 5].map((n) => said(n === 5 ? line(9) : line(n, "e".repeat(40)))) } }, (n) => (n === 9 ? merged : { state: "OPEN" }));
  assert.match(text(five), /pull\/9 merged at b{40}: merged at/);
});

test("a manual close with no line stays unresolved: a link, a non-owner's line and a missing comment all fail", async () => {
  for (const comments of [[], [said("Fixed by https://github.com/acme/app/pull/9")], [said(line(), "NONE")], [said(`prefix ${line()} suffix`)]])
    assert.match(text(await run({ comments: { nodes: comments } })), /the close does not count/);
});


test("a completed close needs the merged PR, not just its closer's word", async () => {
  const closer = { author: { login: "someone" }, authorAssociation: "OWNER", createdAt: "2026-11-19T10:04:50Z", body: "done" };
  assert.match(text(await run({ comments: { nodes: [closer] } })), /the close does not count/);
});

test("a not-planned or duplicate close counts only on the exact reason line, near the close and since the latest reopen", async () => {
  const at = (body: string, createdAt = "2026-11-19T10:04:50Z", authorAssociation = "OWNER") => ({ author: { login: "someone" }, authorAssociation, createdAt, body });
  const counts = async (comment: object, extra: object = {}) => !/does not count/.test(text(await run({ stateReason: "NOT_PLANNED", ...extra, comments: { nodes: [comment] } })));
  assert.equal(await counts(at("Not fixing: src/a.ts:3 shows it.\n\n🤖 Generated by Aiden")), true);
  assert.equal(await counts(at("Duplicate of acme/app#3")), true);
  // An unrelated nearby comment, a near-miss, or a non-owner's line is no reason.
  assert.equal(await counts(at("Not a bug: src/a.ts:3 shows it.")), false);
  assert.equal(await counts(at("Not fixing:")), false);
  assert.equal(await counts(at("Duplicate of #3")), false);
  assert.equal(await counts(at("see Not fixing: x")), false);
  assert.equal(await counts(at("Not fixing: x", "2026-11-19T10:04:50Z", "NONE")), false);
  // Another owner's line is not the closer's: only the one who closed it gives the reason.
  assert.equal(await counts({ ...at("Not fixing: x"), author: { login: "other-owner" } }), false);
  // An unknown closer (a deleted user, no actor) never matches an author-less comment.
  const ghost = { ...at("Not fixing: x"), author: null };
  assert.equal(await counts(ghost, { closedEvents: { nodes: [{ actor: null, closer: null }] } }), false);
  assert.equal(await counts(ghost, { closedEvents: { nodes: [] } }), false);
  // Far from the close (an hour before, a day after) it does not count.
  for (const createdAt of ["2026-11-19T09:00:00Z", "2026-11-20T10:05:00Z"]) assert.equal(await counts(at("Not fixing: x", createdAt)), false);
  // A reopen less than two minutes after an earlier close: that close's line predates the reopen and doesn't count.
  const quick = { reopenedEvents: { nodes: [{ createdAt: "2026-11-19T10:04:55Z" }] }, closedAt: "2026-11-19T10:06:00Z" };
  assert.equal(await counts(at("Not fixing: x"), quick), false);
  assert.equal(await counts(at("Not fixing: x", "2026-11-19T10:05:30Z"), quick), true);
});

test("an open issue left by a `fixed` verdict counts only on the same merged-at-sha check", async () => {
  const open = { state: "OPEN", stateReason: null, closedAt: null, closedEvents: { nodes: [] }, labels: { nodes: [{ name: "fixed" }] } };
  const counted = await run({ ...open, comments: { nodes: [said(line())] } });
  assert.match(text(counted), /acme\/app\/pull\/9 merged at b{40}: merged at/);
  assert.match(counted.version, /@open\+b{12}$/);
  // A wrong PR, an unmerged one, or none at all leaves it unresolved.
  assert.match(text(await run({ ...open, comments: { nodes: [said("Duplicate of acme/app#3")] } })), /^acme\/app#7: open;/);
  assert.doesNotMatch(text(await run({ ...open, comments: { nodes: [said("Duplicate of acme/app#3")] } })), /open\+/);
  assert.match(text(await run({ ...open, comments: { nodes: [said(line())] } }, () => ({ state: "OPEN" }))), /open, not merged/);
  assert.match(text(await run({ ...open, comments: { nodes: [said(line(9, "d".repeat(40)))] } })), /not that sha/);
});
