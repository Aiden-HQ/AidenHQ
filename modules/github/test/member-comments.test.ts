// Members' review comments nobody answered: which threads and conversation comments are open, and that they stand where code
// review's findings do in the decision (before approval and merge), read only when no earlier gate decides.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { openMemberComments, readMemberComments } from "../service/src/member-comments.ts";
import { createMerges } from "../service/src/merges.ts";

const FOOTER = "\n\n🤖 Generated by Engineer with [AidenHQ](https://aidenhq.ai)";
const user = (login: string) => ({ __typename: "User", login });
const th = (id: string, o: { first?: string; resolved?: boolean; n?: number; last?: string; lastBy?: string; bot?: boolean }) => ({
  id, isResolved: o.resolved ?? false, path: "a.ts", line: 3,
  comments: { nodes: [{ author: o.bot ? { __typename: "Bot", login: "app" } : user(o.first ?? "maxsam4"), authorAssociation: "MEMBER" }] },
  last: { totalCount: o.n ?? 1, nodes: [{ fullDatabaseId: `${id}-last`, body: o.last ?? "please fix", author: user(o.lastBy ?? "maxsam4"), authorAssociation: "MEMBER" }] },
});
const note = (id: string, who: string, at: string, body: string, bot = false) => ({ fullDatabaseId: id, createdAt: at, body, author: bot ? { __typename: "Bot", login: who } : user(who), authorAssociation: "MEMBER" });
const isMember = async (login: string) => login !== "stranger";

test("open member threads and conversation comments: answered, resolved, outsiders, bots, the author and commands are not", async () => {
  const pr = {
    author: { login: "me" },
    reviewThreads: { nodes: [
      th("open", {}), th("answered", { n: 2, last: `declined: no${FOOTER}` }), th("forged", { n: 2, last: `declined: no${FOOTER}`, lastBy: "stranger" }), th("signed-finding", { last: `a finding${FOOTER}` }), th("resolved", { resolved: true }),
      th("outsider", { first: "stranger" }), th("bot", { bot: true }), th("followup", { n: 3, last: "still wrong" }),
    ] },
    comments: { nodes: [
      note("1", "maria", "2026-11-24T00:00:00Z", "before the hand-off"),
      note("2", "maria", "2026-11-24T02:00:00Z", "please rename it"),
      note("3", "me", "2026-11-24T02:01:00Z", "the author's own words"),
      note("4", "maria", "2026-11-24T02:02:00Z", "/ship"),
      note("5", "stranger", "2026-11-24T02:03:00Z", "an outsider"),
      note("6", "coderabbit", "2026-11-24T02:04:00Z", "a bot", true),
      note("7", "maria", "2026-11-24T03:00:00Z", "and move it"),
      note("8", "me", "2026-11-24T03:30:00Z", `7: fixed in abc: renamed${FOOTER}`),
      note("9", "maria", "2026-11-24T04:00:00Z", "one more"),
      note("10", "stranger", "2026-11-24T05:00:00Z", `an outsider's copy of the footer${FOOTER}`),
    ] },
  };
  const items = await openMemberComments(pr, { since: "2026-11-24T01:00:00Z", author: "me", isMember });
  assert.deepEqual(items.map((i) => i.id), ["thread:open:open-last", "thread:forged:forged-last", "thread:signed-finding:signed-finding-last", "thread:followup:followup-last", "comment:2", "comment:9"], "an outsider's copy of the footer answers nothing, and a reply answers only the ids it names");
  // The author's own comment asks nothing on a member's PR, but on a PR the code host opened as the owner it is the owner's word.
  const own = { reviewThreads: { nodes: [] }, comments: { nodes: [note("3", "me", "2026-11-24T02:01:00Z", "please rename it")] } };
  assert.deepEqual([(await openMemberComments(own, { since: "2026-11-24T01:00:00Z", author: "me", isMember })).length, (await openMemberComments(own, { since: "2026-11-24T01:00:00Z", isMember })).length], [0, 1]);
});

test("a PR with more threads and comments than a page is read back to the hand-off, and one that can't be is an error, never a clear PR", async () => {
  const pages = [
    { reviewThreads: { pageInfo: { hasPreviousPage: true, startCursor: "t2" }, nodes: [th("c", {})] }, comments: { pageInfo: { hasPreviousPage: true, startCursor: "c2" }, nodes: [note("3", "maria", "2026-11-24T03:00:00Z", "late")] } },
    { reviewThreads: { pageInfo: { hasPreviousPage: false }, nodes: [th("a", {})] }, comments: { pageInfo: { hasPreviousPage: true, startCursor: "c1" }, nodes: [note("2", "maria", "2026-11-24T02:00:00Z", "mid")] } },
  ];
  const asked: unknown[] = [];
  const pr = await readMemberComments(async (t, c) => (asked.push([t, c]), pages[asked.length - 1]), "2026-11-24T02:30:00Z");
  assert.deepEqual(asked, [[null, null], ["t2", "c2"]], "comments older than the hand-off are not fetched");
  assert.deepEqual([pr.reviewThreads.nodes.map((n: any) => n.id), pr.comments.nodes.map((n: any) => n.fullDatabaseId)], [["a", "c"], ["2", "3"]]);
  const endless = { reviewThreads: { pageInfo: { hasPreviousPage: true, startCursor: "t" }, nodes: [] }, comments: { nodes: [] } };
  await assert.rejects(readMemberComments(async () => endless, "2026-11-24T00:00:00Z"), /more comments than can be read/);
});

test("a decision asked for member comments is fix_review ahead of approval and merge, reads them only past repair and red CI, and fails when it can't read", async () => {
  const H = "b".repeat(40), graphql: string[] = [];
  let data: any = { author: { login: "me" }, reviewThreads: { nodes: [th("open", {})] }, comments: { nodes: [] } };
  const gh = async (method: string, path: string, body?: any) => {
    if (path === "/graphql") { graphql.push(body.query); return data ? { status: 200, body: { data: { repository: { pullRequest: data } } } } : { status: 502, body: {} }; }
    return path.includes("/rules/branches/") ? { status: 200, body: [{ type: "required_status_checks", parameters: { required_status_checks: [{ context: "build" }] } }] } : { status: 404, body: {} };
  };
  const flow = { isMember: async () => true } as any;
  const merges = createMerges({ dir: mkdtempSync(join(tmpdir(), "member-decision-")), gh, fleetOrg: "acme-agents", reviewGate: async () => ({ pass: true }), report: async () => {}, flow });
  const rollup = (conclusion: string) => ({ state: "SUCCESS", contexts: { pageInfo: { hasNextPage: false }, nodes: [{ __typename: "CheckRun", name: "build", status: "COMPLETED", conclusion }] } });
  const view = (conclusion = "SUCCESS", state = "CLEAN") => ({ pr: { number: 3, headRefOid: H, baseRefName: "main", mergeStateStatus: state, reviewDecision: null, isDraft: false, isInMergeQueue: false, latestOpinionatedReviews: { nodes: [] }, commits: { nodes: [{ commit: { statusCheckRollup: rollup(conclusion) } }] } }, main: { name: "main", oid: "c".repeat(40), rollup: { state: "SUCCESS" } }, comments: { since: "2026-11-24T01:00:00Z" } });
  const asked = await merges.decision("acme-agents/widget", 3, H, view()) as any;
  assert.equal(asked.do, "fix_review");
  assert.deepEqual(asked.memberComments.map((i: any) => i.id), ["thread:open:open-last"]);
  data = { author: { login: "me" }, reviewThreads: { nodes: [] }, comments: { nodes: [] } };
  assert.equal((await merges.decision("acme-agents/widget", 3, H, view()) as any).do, "merge", "nothing open: ready");
  graphql.length = 0;
  assert.equal((await merges.decision("acme-agents/widget", 3, H, view("FAILURE")) as any).do, "fix_ci");
  assert.equal((await merges.decision("acme-agents/widget", 3, H, view("SUCCESS", "BEHIND")) as any).do, "repair");
  assert.equal(graphql.length, 0, "red CI and a behind branch decide before any comment is read");
  data = undefined;
  await assert.rejects(merges.decision("acme-agents/widget", 3, H, view()), /couldn't be read/);
});
