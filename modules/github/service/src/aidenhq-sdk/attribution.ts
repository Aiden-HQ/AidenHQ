// How AidenHQ signs what it writes on GitHub as the owner (spec 2026-11-20-github-owner-identity §4; owner, 2026-11-20): every
// commit carries a trailer naming the agent, every posted text ends with a footer naming it and linking AidenHQ. Readers
// (flow.ts author_kind) match only the fixed parts, never the names: the noreply address and the link.
//
// First-party modules hold byte-identical copies (scripts/sync-shared.ts: edit this one and run it).

/** The fixed address in every trailer. */
export const TRAILER_EMAIL = "noreply@aidenhq.ai";
/** The fixed link in every footer. */
export const FOOTER_LINK = "https://aidenhq.ai";

/** `Co-authored-by: AidenHQ <agent> <noreply@aidenhq.ai>` */
export const trailer = (agent: string) => `Co-authored-by: AidenHQ ${agent} <${TRAILER_EMAIL}>`;
/** `🤖 Generated by <agent> with [AidenHQ](https://aidenhq.ai)` */
export const footer = (agent: string) => `🤖 Generated by ${agent} with [AidenHQ](${FOOTER_LINK})`;

/** A commit message ending with the agent's trailer (once: a message already carrying an AidenHQ trailer keeps it). */
export const withTrailer = (message: string, agent: string) => (hasTrailer(message) ? message : [message.trimEnd(), trailer(agent)].filter(Boolean).join("\n\n"));
/** A posted text ending with the agent's footer (once). */
export const withFooter = (text: string, agent: string) => (hasFooter(text) ? text : [text.trimEnd(), footer(agent)].filter(Boolean).join("\n\n"));

/** Whether a commit message carries an AidenHQ trailer (any agent). */
export const hasTrailer = (message: string) => new RegExp(`^Co-authored-by: AidenHQ .*<${TRAILER_EMAIL.replace(/\./g, "\\.")}>\\s*$`, "im").test(message);
/** Whether a text carries an AidenHQ footer (any agent). */
export const hasFooter = (text: string) => text.includes(`](${FOOTER_LINK})`);
