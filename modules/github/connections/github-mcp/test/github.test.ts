import { describe, expect, it } from "vitest";
import { GitHub, GitHubRefused, GRAPHQL, guard } from "../src/github.js";
import { accessFor } from "./fake-access.js";

/** The owner's GitHub over the fake: the client (src/client.ts) and the job-log fetch both use it. */
const owner = (impl: typeof fetch, token = "gho_test") => new GitHub(accessFor((url, init) => impl(url, init), token), impl);
const FOOTER = (agent: string) => `🤖 Generated by ${agent} with [AidenHQ](https://aidenhq.ai)`;

/** A fake GitHub that records every request and answers from `routes` (pathname → body). */
function fake(routes: Record<string, unknown>) {
  const calls: { method: string; url: URL; body?: unknown; auth?: string }[] = [];
  const impl = (async (input: URL | string, init?: RequestInit) => {
    const url = new URL(String(input));
    calls.push({ method: init?.method ?? "GET", url, body: init?.body ? JSON.parse(String(init.body)) : undefined, auth: (init?.headers as Record<string, string>)?.authorization });
    const key = `${init?.method ?? "GET"} ${url.pathname}${url.searchParams.get("page") ? `?page=${url.searchParams.get("page")}` : ""}`;
    const hit = routes[key] ?? routes[`${init?.method ?? "GET"} ${url.pathname}`];
    if (hit === undefined) return new Response("Not Found", { status: 404 });
    return new Response(JSON.stringify(hit), { status: 200 });
  }) as typeof fetch;
  return { impl, calls };
}

describe("guard", () => {
  it("allows the read endpoints and the writes the user can ask for", () => {
    for (const [m, p] of [
      ["GET", "/user"],
      ["GET", "/repos/example-org/issue-tracker/issues/7334"],
      ["GET", "/repos/example-org/issue-tracker/issues/7334/comments"],
      ["GET", "/repos/a/b/pulls/3"],
      ["GET", "/repos/a/b/pulls/3/reviews"],
      ["GET", "/repos/a/b/commits/0123456789abcdef0123456789abcdef01234567/check-runs"],
      ["GET", "/search/issues"],
      ["POST", "/repos/a/b/issues/3/comments"],
      ["POST", "/repos/a/b/issues"],
      ["GET", "/repos/a/b/labels"],
      ["GET", "/repos/a/b/actions/runs"],
      ["GET", "/repos/a/b/actions/runs/123"],
      ["GET", "/repos/a/b/actions/jobs/123/logs"],
      ["POST", "/repos/a/b/issues/3/labels"],
      ["DELETE", "/repos/a/b/issues/3/labels/needs%20triage"],
      ["POST", "/repos/a/b/issues/3/assignees"],
      ["DELETE", "/repos/a/b/issues/3/assignees"],
      ["POST", "/repos/a/b/actions/runs/123/rerun-failed-jobs"],
    ] as const)
      expect(() => guard(m, p)).not.toThrow();
    expect(() => guard("PATCH", "/repos/a/b/issues/3", { state: "closed", state_reason: "not_planned" })).not.toThrow();
    expect(() => guard("POST", "/repos/a/b/pulls/3/reviews", { event: "COMMENT", commit_id: "abc", body: "x" })).not.toThrow();
    for (const query of Object.values(GRAPHQL)) expect(() => guard("POST", "/graphql", { query })).not.toThrow();
  });

  it("limits what an issue edit and a review may carry", () => {
    for (const body of [{ title: "x" }, { body: "x", title: "y" }, { state: "closed", assignees: [] }, { milestone: 1 }])
      expect(() => guard("PATCH", "/repos/a/b/issues/3", body), JSON.stringify(body)).toThrow(GitHubRefused);
    // A comment review only: an approval or change request as the owner would count as the owner's own review.
    for (const body of [undefined, { body: "x" }, { event: "DISMISS" }, { event: "APPROVE" }, { event: "REQUEST_CHANGES", body: "x" }, { event: "APPROVE", comments: [] }])
      expect(() => guard("POST", "/repos/a/b/pulls/3/reviews", body), JSON.stringify(body)).toThrow(GitHubRefused);
  });

  it("refuses GraphQL that isn't one of the fixed documents", () => {
    for (const body of [undefined, {}, { query: "mutation { deleteRepository(input: { repositoryId: \"x\" }) { clientMutationId } }" }, { query: GRAPHQL.addItem + " " }])
      expect(() => guard("POST", "/graphql", body), JSON.stringify(body)).toThrow(GitHubRefused);
  });

  it("refuses everything else the token could do", () => {
    for (const [m, p] of [
      ["DELETE", "/repos/a/b/issues/comments/9"],
      ["PUT", "/repos/a/b/pulls/3/merge"],
      ["DELETE", "/repos/a/b/git/refs/heads/main"],
      ["PUT", "/repos/a/b/contents/README.md"],
      ["GET", "/repos/a/b/contents/README.md"],
      ["GET", "/repos/a/b/issues/3/comments/../../../../user/keys"],
      ["PUT", "/repos/a/b/issues/3/labels"], // replace all labels
      ["DELETE", "/repos/a/b/issues/3/labels"], // remove all labels
      ["POST", "/repos/a/b/actions/runs/123/rerun"], // re-run every job, passing ones too
      ["POST", "/repos/a/b/actions/runs/123/cancel"],
      ["POST", "/repos/a/b/pulls/3/reviews/9/dismissals"],
      ["GET", "/graphql"],
      ["POST", "/repos/a/b/labels"],
    ] as const)
      expect(() => guard(m, p), `${m} ${p}`).toThrow(GitHubRefused);
    // A review's text may be updated (code review links its threads), nothing else of it.
    expect(() => guard("PUT", "/repos/a/b/pulls/3/reviews/9", { body: "x" })).not.toThrow();
    expect(() => guard("PUT", "/repos/a/b/pulls/3/reviews/9", { body: "x", event: "APPROVE" })).toThrow(GitHubRefused);
  });

  it("refuses paths that URL resolution would move", async () => {
    const { impl, calls } = fake({});
    const gh = owner(impl);
    await expect(gh.request("GET", "/repos/../../user/issues/1")).rejects.toBeInstanceOf(GitHubRefused);
    await expect(gh.comment({ owner: "a", repo: "..", number: 1 }, "x", "Aiden")).rejects.toBeInstanceOf(GitHubRefused);
    expect(calls).toHaveLength(0);
  });
});

describe("owner-token label writes", () => {
  it("refuse agent-build in any case, on update and on create, before anything is written", async () => {
    const { impl, calls } = fake({ "GET /repos/a/b/issues/7": { number: 7, labels: [], state: "open" } });
    const gh = owner(impl);
    await expect(gh.createIssue({ repo: "a/b", title: "t", body: "b", labels: ["Agent-Build"] }, "Aiden")).rejects.toThrow("agent-build is the owner's label");
    await expect(gh.updateIssue({ owner: "a", repo: "b", number: 7 }, { addLabels: ["agent-build"] })).rejects.toThrow("agent-build is the owner's label");
    expect(calls.filter((c) => c.method !== "GET")).toHaveLength(0);
  });
});

describe("issue body refresh", () => {
  it("replaces an issue's body, signed, with no second issue; a pull request's text is refused", async () => {
    const { impl, calls } = fake({ "GET /repos/a/b/issues/41": { number: 41, labels: [], state: "closed", html_url: "https://github.com/a/b/issues/41" }, "PATCH /repos/a/b/issues/41": {}, "GET /repos/a/b/issues/9": { number: 9, labels: [], state: "open", pull_request: {} } });
    const gh = owner(impl);
    const out = await gh.updateIssue({ owner: "a", repo: "b", number: 41 }, { body: "<!-- aidenhq-ui:design:acme -->\nnew report", state: "open" }, "UI Reviewer") as { done: string[] };
    const writes = calls.filter((c) => c.method !== "GET");
    expect(writes.map((c) => `${c.method} ${c.url.pathname}`)).toEqual(["PATCH /repos/a/b/issues/41", "PATCH /repos/a/b/issues/41"]);
    expect((writes[0]!.body as { body: string }).body).toMatch(/^<!-- aidenhq-ui:design:acme -->\nnew report[\s\S]*UI Reviewer/);
    expect(out.done).toEqual(["replaced the body", "reopened"]);
    await expect(gh.updateIssue({ owner: "a", repo: "b", number: 9 }, { body: "x" }, "UI Reviewer")).rejects.toThrow("pull request's text");
  });
});

describe("GitHub", () => {

  it("refuses a log redirect to any other host without fetching it", async () => {
    const calls: string[] = [];
    const impl = (async (input: URL | string) => {
      calls.push(String(input));
      return new Response(null, { status: 302, headers: { location: "https://evil.example.com/log" } });
    }) as typeof fetch;
    await expect(owner(impl).jobLog("a/b", 5)).rejects.toThrow("no log download");
    expect(calls).toHaveLength(1);
  });

  describe("createIssue", () => {
    const project = {
      data: {
        organization: {
          projectV2: {
            id: "P1",
            title: "Acme Wallet",
            url: "https://github.com/orgs/example-org/projects/16",
            closed: false,
            field: { id: "F1", options: [{ id: "o1", name: "❄  Icebox" }, { id: "o2", name: "🔍  Triage" }] },
            items: { nodes: [{ content: { repository: { nameWithOwner: "example-org/issue-tracker" } } }, { content: { repository: { nameWithOwner: "example-org/issue-tracker" } } }, { content: { repository: { nameWithOwner: "example-org/other" } } }, { content: null }] },
          },
        },
      },
    };
    const created = { number: 9, node_id: "I9", html_url: "https://github.com/example-org/issue-tracker/issues/9", labels: [{ name: "waas" }] };
    /** GraphQL answers by document. */
    function gql(answers: Partial<Record<keyof typeof GRAPHQL, unknown>>, rest: Record<string, unknown> = {}) {
      const f = fake(rest);
      const impl = (async (input: URL | string, init?: RequestInit) => {
        if (new URL(String(input)).pathname !== "/graphql") return f.impl(input, init);
        const { query } = JSON.parse(String(init!.body));
        const name = (Object.keys(GRAPHQL) as (keyof typeof GRAPHQL)[]).find((k) => GRAPHQL[k] === query)!;
        f.calls.push({ method: "POST", url: new URL(String(input)), body: { doc: name, ...JSON.parse(String(init!.body)).variables } });
        return new Response(JSON.stringify(answers[name] ?? { errors: [{ message: "no" }] }), { status: 200 });
      }) as typeof fetch;
      return { impl, calls: f.calls };
    }

    it("opens the issue in the project's repository with labels and a status", async () => {
      const { impl, calls } = gql(
        { project, addItem: { data: { addProjectV2ItemById: { item: { id: "IT1" } } } }, setStatus: { data: { updateProjectV2ItemFieldValue: { projectV2Item: { id: "IT1" } } } } },
        { "GET /repos/example-org/issue-tracker/labels": [{ name: "bug" }, { name: "waas" }], "POST /repos/example-org/issue-tracker/issues": created },
      );
      const out = await owner(impl).createIssue({ title: "T", body: "B", labels: ["WaaS"], project: "https://github.com/orgs/Example-Org/projects/16/views/17", status: "triage" }, "Aiden");
      expect(out).toEqual({ repo: "example-org/issue-tracker", number: 9, url: created.html_url, labels: ["waas"], objects: ["github:example-org/issue-tracker#9"], project: { title: "Acme Wallet", url: project.data.organization.projectV2.url, added: true, status: "🔍  Triage" } });
      expect(calls.find((c) => c.url.pathname.endsWith("/issues"))?.body).toEqual({ title: "T", body: `B\n\n${FOOTER("Aiden")}`, labels: ["waas"] });
      expect(calls.at(-1)?.body).toEqual({ doc: "setStatus", project: "P1", item: "IT1", field: "F1", option: "o2" });
    });

  });

  describe("what closed an issue", () => {
    const closed = (node: unknown) => {
      const impl = (async (input: URL | string, init?: RequestInit) => {
        const url = new URL(String(input));
        if (url.pathname === "/graphql") return new Response(JSON.stringify({ data: { repository: { issue: { closedEvents: { nodes: [node] } } } } }), { status: 200 });
        if (url.pathname.endsWith("/comments")) return new Response("[]", { status: 200 });
        return new Response(JSON.stringify({ number: 5, state: "closed", html_url: "u", title: "t", comments: 0, labels: [], user: { login: "x" } }), { status: 200 });
      }) as typeof fetch;
      return owner(impl).read({ owner: "a", repo: "b", number: 5 }) as Promise<{ closed_by?: unknown }>;
    };

    it("github_issue_read names the merged PR whose Fixes line closed it, or the commit", async () => {
      expect((await closed({ actor: { login: "bot" }, closer: { __typename: "PullRequest", number: 9, state: "MERGED", mergeCommit: { oid: "abc" }, repository: { nameWithOwner: "a/b" } } })).closed_by)
        .toEqual({ actor: "bot", pull_request: { repo: "a/b", number: 9, merged: true, merge_commit_sha: "abc" } });
      expect((await closed({ actor: { login: "me" }, closer: { __typename: "Commit", oid: "def" } })).closed_by).toEqual({ actor: "me", commit: "def" });
      expect((await closed({ actor: { login: "me" }, closer: null })).closed_by).toEqual({ actor: "me" });
    });
  });

  describe("a failed closer lookup", () => {
    it("leaves the issue readable and says the attribution is unavailable", async () => {
      const impl = (async (input: URL | string) => {
        const url = new URL(String(input));
        if (url.pathname === "/graphql") return new Response(JSON.stringify({ message: "rate limited" }), { status: 502 });
        if (url.pathname.endsWith("/comments")) return new Response("[]", { status: 200 });
        return new Response(JSON.stringify({ number: 5, state: "closed", html_url: "u", title: "t", comments: 0, labels: [], user: { login: "x" } }), { status: 200 });
      }) as typeof fetch;
      const out = (await owner(impl).read({ owner: "a", repo: "b", number: 5 })) as { state: string; closed_by?: unknown; closed_by_error?: string };
      expect(out.state).toBe("closed");
      expect(out.closed_by).toBeUndefined();
      expect(out.closed_by_error).toBeTruthy();
    });
  });

  describe("review thread replies", () => {
    const PR_URL = "https://api.github.com/repos/a/b/pulls/7";
    const reply = (id: number, parent?: number, pull = PR_URL) => ({ id, pull_request_url: pull, ...(parent === undefined ? { in_reply_to_id: null } : { in_reply_to_id: parent }) });
    /**
     * A fake GitHub that answers a direct read of each comment in `comments` (by id), the reply write with `answer`, and any
     * other read with a 404. No review threads are listed at all: the lookup must not depend on that listing.
     */
    function fakeReplies(comments: Record<number, unknown>, answer: () => Response = () => new Response(JSON.stringify({ id: 77, html_url: "https://github.com/a/b/pull/7#discussion_r77" }), { status: 201 }), prUrl = PR_URL) {
      const calls: { method: string; path: string; body?: any }[] = [];
      const impl = (async (input: URL | string, init?: RequestInit) => {
        const url = new URL(String(input));
        const method = init?.method ?? "GET";
        calls.push({ method, path: url.pathname, body: init?.body ? JSON.parse(String(init.body)) : undefined });
        if (method === "POST" && /\/pulls\/\d+\/comments\/\d+\/replies$/.test(url.pathname)) return answer();
        if (method === "GET" && /^\/repos\/[^/]+\/[^/]+\/pulls\/7$/.test(url.pathname)) return new Response(JSON.stringify({ url: prUrl }), { status: 200 });
        const m = url.pathname.match(/^\/repos\/([^/]+)\/([^/]+)\/pulls\/comments\/(\d+)$/);
        if (method === "GET" && m && comments[Number(m[3])]) return new Response(JSON.stringify(comments[Number(m[3])]), { status: 200 });
        return new Response(JSON.stringify({ message: "Not Found" }), { status: 404 });
      }) as typeof fetch;
      return { impl, calls };
    }
    const posts = (calls: { method: string; path: string; body?: any }[]) => calls.filter((c) => c.method === "POST" && !c.path.endsWith("/graphql"));

    it("a reply id resolves to its thread's first comment, which the POST names", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100), 101: reply(101, 100), 102: reply(102, 100) });
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 101, "fixed: abc1234.", "Aiden")).resolves.toEqual({ id: 77, url: "https://github.com/a/b/pull/7#discussion_r77" });
      const post = posts(calls)[0]!;
      expect(post.path).toBe("/repos/a/b/pulls/7/comments/100/replies");
      expect(post.body.body).toContain(`fixed: abc1234.\n\n${FOOTER("Aiden")}`);
    });

    it("resolveThread resolves the thread the comment is in, and a refusal or a missing thread throws", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100), 101: reply(101, 100) });
      const graph = (resolveAnswer: () => Response) => (async (input: URL | string, init?: RequestInit) => {
        if (!new URL(String(input)).pathname.endsWith("/graphql")) return impl(input, init);
        const q = JSON.parse(String(init!.body)).query as string;
        calls.push({ method: "POST", path: "/graphql:" + (q.includes("resolveReviewThread") ? "resolve" : "threads") });
        if (q.includes("resolveReviewThread")) return resolveAnswer();
        return new Response(JSON.stringify({ data: { repository: { pullRequest: { reviewThreads: { pageInfo: { hasNextPage: false, endCursor: null }, nodes: [{ id: "T9", comments: { nodes: [{ fullDatabaseId: "99" }] } }, { id: "T1", comments: { nodes: [{ fullDatabaseId: "100" }] } }] } } } } }), { status: 200 });
      }) as typeof fetch;
      const ok = await owner(graph(() => new Response(JSON.stringify({ data: { t0: { thread: { id: "T1", isResolved: true } } } }), { status: 200 }))).resolveThread({ owner: "a", repo: "b", number: 7 }, 101);
      expect(ok).toEqual({ resolved: true });
      expect(calls.map((c) => c.path).filter((p) => p.startsWith("/graphql"))).toEqual(["/graphql:threads", "/graphql:resolve"]);
      await expect(owner(graph(() => new Response(JSON.stringify({ errors: [{ message: "Resource not accessible" }] }), { status: 200 }))).resolveThread({ owner: "a", repo: "b", number: 7 }, 100)).rejects.toThrow(/not accessible/);
    });

    it("a thread root's id is used as it is", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100) });
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "disputed: see src/a.ts:3.", "Aiden");
      expect(posts(calls)[0]!.path).toBe("/repos/a/b/pulls/7/comments/100/replies");
    });

    it("resolves ids past the 32-bit range", async () => {
      const { impl, calls } = fakeReplies({ 4_657_268_819: reply(4_657_268_819), 4_657_373_830: reply(4_657_373_830, 4_657_268_819) });
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 4_657_373_830, "fixed: 58099a73.", "Aiden");
      expect(posts(calls)[0]!.path).toBe("/repos/a/b/pulls/7/comments/4657268819/replies");
    });

    it("a root far past any thread listing still resolves: the lookup reads the comment itself", async () => {
      const { impl, calls } = fakeReplies({ 9_000_001: reply(9_000_001) });
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 9_000_001, "fixed: abc1234.", "Aiden");
      expect(calls.some((c) => c.path === "/graphql")).toBe(false);
      expect(posts(calls)[0]!.path).toBe("/repos/a/b/pulls/7/comments/9000001/replies");
    });

    it("walks a longer reply chain to its top-level comment", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100), 101: reply(101, 100), 102: reply(102, 101) });
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 102, "fixed: abc1234.", "Aiden");
      expect(posts(calls)[0]!.path).toBe("/repos/a/b/pulls/7/comments/100/replies");
    });

    it("an id that isn't a review comment of the pull request fails with its reason, and nothing is posted", async () => {
      const { impl, calls } = fakeReplies({});
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(GitHubRefused);
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(/comment 999 isn't a review comment of a\/b/);
      expect(posts(calls)).toHaveLength(0);
    });

    it("a comment on another pull request is refused, and nothing is posted", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100, undefined, "https://api.github.com/repos/a/b/pulls/8") });
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "fixed: abc1234.", "Aiden")).rejects.toThrow(/is on https:\/\/api\.github\.com\/repos\/a\/b\/pulls\/8, not a\/b#7/);
      expect(posts(calls)).toHaveLength(0);
    });

    it("a broken reply chain is refused, and nothing is posted", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100, 101), 101: reply(101, 100) });
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "fixed: abc1234.", "Aiden")).rejects.toThrow(/broken reply chain/);
      expect(posts(calls)).toHaveLength(0);
    });

    it("a lookup that fails upstream (not a 404) is passed on, not reported as a missing comment", async () => {
      const calls: { method: string; path: string }[] = [];
      const impl = (async (input: URL | string, init?: RequestInit) => {
        const url = new URL(String(input));
        calls.push({ method: init?.method ?? "GET", path: url.pathname });
        if ((init?.method ?? "GET") === "GET" && url.pathname === "/repos/a/b/pulls/7") return new Response(JSON.stringify({ url: PR_URL }), { status: 200 });
        if ((init?.method ?? "GET") === "GET" && /^\/repos\/a\/b\/pulls\/comments\/\d+$/.test(url.pathname)) return new Response(JSON.stringify({ message: "Server Error" }), { status: 503 });
        return new Response("Not Found", { status: 404 });
      }) as typeof fetch;
      const err = await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "fixed: abc1234.", "Aiden").catch((e) => e);
      expect(err).toBeInstanceOf(Error);
      expect(err).not.toBeInstanceOf(GitHubRefused);
      expect(String(err.message)).toMatch(/GitHub 503/);
      expect(calls.some((c) => c.method === "POST")).toBe(false);
    });

    it("a repository renamed since the caller's URL still replies, on the canonical name", async () => {
      const { impl, calls } = fakeReplies({ 100: reply(100, undefined, "https://api.github.com/repos/a/new-name/pulls/7") }, undefined, "https://api.github.com/repos/a/new-name/pulls/7");
      await owner(impl).reply({ owner: "a", repo: "old-name", number: 7 }, 100, "fixed: abc1234.", "Aiden");
      expect(calls.some((c) => c.path === "/repos/a/new-name/pulls/comments/100")).toBe(true);
      expect(posts(calls)[0]!.path).toBe("/repos/a/new-name/pulls/7/comments/100/replies");
    });

    it("a 422 surfaces GitHub's errors[] field and code", async () => {
      const { impl } = fakeReplies({ 100: reply(100) }, () => new Response(JSON.stringify({ message: "Validation Failed", errors: [{ resource: "PullRequestReviewComment", field: "body", code: "custom", message: "body is too long" }] }), { status: 422 }));
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "x", "Aiden")).rejects.toThrow(/Validation Failed; PullRequestReviewComment\.body: custom: body is too long/);
    });
  });

  describe("issue, review and re-run writes", () => {
    it("pr review posts COMMENT only, at the head it read, signed by the agent", async () => {
      const { impl, calls } = fake({ "GET /repos/a/b/pulls/7": { state: "open", head: { sha: "abc" } }, "POST /repos/a/b/pulls/7/reviews": { id: 5, html_url: "h", state: "COMMENTED" } });
      const gh = owner(impl);
      await expect(gh.review({ owner: "a", repo: "b", number: 7 }, "Looks fine.", "Aiden")).resolves.toEqual({ id: 5, url: "h", state: "COMMENTED" });
      expect(calls.at(-1)?.body).toEqual({ event: "COMMENT", commit_id: "abc", body: `Looks fine.\n\n${FOOTER("Aiden")}` });
      await expect(gh.review({ owner: "a", repo: "b", number: 7 }, " ", "Aiden")).rejects.toBeInstanceOf(GitHubRefused);
    });

  });

});
