import { describe, expect, it } from "vitest";
import { GitHub, GitHubRefused, GRAPHQL, guard } from "../src/github.js";
import { accessFor } from "./fake-access.js";

/** The owner's GitHub over the fake: the client (src/client.ts) and the job-log fetch both use it. */
const owner = (impl: typeof fetch, token = "gho_test") => new GitHub(accessFor((url, init) => impl(url, init), token), impl);
const FOOTER = (agent: string) => `🤖 Generated by ${agent} with [AidenHQ](https://aidenhq.ai)`;

/** A fake GitHub that records every request and answers from `routes` (pathname → body). */
function fake(routes: Record<string, unknown>) {
  const calls: { method: string; url: URL; body?: unknown; auth?: string }[] = [];
  const impl = (async (input: URL | string, init?: RequestInit) => {
    const url = new URL(String(input));
    calls.push({ method: init?.method ?? "GET", url, body: init?.body ? JSON.parse(String(init.body)) : undefined, auth: (init?.headers as Record<string, string>)?.authorization });
    const key = `${init?.method ?? "GET"} ${url.pathname}${url.searchParams.get("page") ? `?page=${url.searchParams.get("page")}` : ""}`;
    const hit = routes[key] ?? routes[`${init?.method ?? "GET"} ${url.pathname}`];
    if (hit === undefined) return new Response("Not Found", { status: 404 });
    return new Response(JSON.stringify(hit), { status: 200 });
  }) as typeof fetch;
  return { impl, calls };
}

describe("guard", () => {
  it("allows the read endpoints and the writes the user can ask for", () => {
    for (const [m, p] of [
      ["GET", "/user"],
      ["GET", "/repos/example-org/issue-tracker/issues/7334"],
      ["GET", "/repos/example-org/issue-tracker/issues/7334/comments"],
      ["GET", "/repos/a/b/pulls/3"],
      ["GET", "/repos/a/b/pulls/3/reviews"],
      ["GET", "/repos/a/b/commits/0123456789abcdef0123456789abcdef01234567/check-runs"],
      ["GET", "/search/issues"],
      ["POST", "/repos/a/b/issues/3/comments"],
      ["POST", "/repos/a/b/issues"],
      ["GET", "/repos/a/b/labels"],
      ["GET", "/repos/a/b/actions/runs"],
      ["GET", "/repos/a/b/actions/runs/123"],
      ["GET", "/repos/a/b/actions/jobs/123/logs"],
      ["POST", "/repos/a/b/issues/3/labels"],
      ["DELETE", "/repos/a/b/issues/3/labels/needs%20triage"],
      ["POST", "/repos/a/b/issues/3/assignees"],
      ["DELETE", "/repos/a/b/issues/3/assignees"],
      ["POST", "/repos/a/b/actions/runs/123/rerun-failed-jobs"],
    ] as const)
      expect(() => guard(m, p)).not.toThrow();
    expect(() => guard("PATCH", "/repos/a/b/issues/3", { state: "closed", state_reason: "not_planned" })).not.toThrow();
    expect(() => guard("POST", "/repos/a/b/pulls/3/reviews", { event: "COMMENT", commit_id: "abc", body: "x" })).not.toThrow();
    for (const query of Object.values(GRAPHQL)) expect(() => guard("POST", "/graphql", { query })).not.toThrow();
  });

  it("limits what an issue edit and a review may carry", () => {
    for (const body of [{ title: "x" }, { state: "closed", body: "x" }, { state: "closed", assignees: [] }, { milestone: 1 }])
      expect(() => guard("PATCH", "/repos/a/b/issues/3", body), JSON.stringify(body)).toThrow(GitHubRefused);
    // A comment review only: an approval or change request as the owner would count as the owner's own review.
    for (const body of [undefined, { body: "x" }, { event: "DISMISS" }, { event: "APPROVE" }, { event: "REQUEST_CHANGES", body: "x" }, { event: "APPROVE", comments: [] }])
      expect(() => guard("POST", "/repos/a/b/pulls/3/reviews", body), JSON.stringify(body)).toThrow(GitHubRefused);
  });

  it("refuses GraphQL that isn't one of the fixed documents", () => {
    for (const body of [undefined, {}, { query: "mutation { deleteRepository(input: { repositoryId: \"x\" }) { clientMutationId } }" }, { query: GRAPHQL.addItem + " " }])
      expect(() => guard("POST", "/graphql", body), JSON.stringify(body)).toThrow(GitHubRefused);
  });

  it("refuses everything else the token could do", () => {
    for (const [m, p] of [
      ["DELETE", "/repos/a/b/issues/comments/9"],
      ["PUT", "/repos/a/b/pulls/3/merge"],
      ["DELETE", "/repos/a/b/git/refs/heads/main"],
      ["PUT", "/repos/a/b/contents/README.md"],
      ["GET", "/repos/a/b/contents/README.md"],
      ["GET", "/repos/a/b/issues/3/comments/../../../../user/keys"],
      ["PUT", "/repos/a/b/issues/3/labels"], // replace all labels
      ["DELETE", "/repos/a/b/issues/3/labels"], // remove all labels
      ["POST", "/repos/a/b/actions/runs/123/rerun"], // re-run every job, passing ones too
      ["POST", "/repos/a/b/actions/runs/123/cancel"],
      ["POST", "/repos/a/b/pulls/3/reviews/9/dismissals"],
      ["GET", "/graphql"],
      ["POST", "/repos/a/b/labels"],
    ] as const)
      expect(() => guard(m, p), `${m} ${p}`).toThrow(GitHubRefused);
    // A review's text may be updated (code review links its threads), nothing else of it.
    expect(() => guard("PUT", "/repos/a/b/pulls/3/reviews/9", { body: "x" })).not.toThrow();
    expect(() => guard("PUT", "/repos/a/b/pulls/3/reviews/9", { body: "x", event: "APPROVE" })).toThrow(GitHubRefused);
  });

  it("refuses paths that URL resolution would move", async () => {
    const { impl, calls } = fake({});
    const gh = owner(impl);
    await expect(gh.request("GET", "/repos/../../user/issues/1")).rejects.toBeInstanceOf(GitHubRefused);
    await expect(gh.comment({ owner: "a", repo: "..", number: 1 }, "x", "Aiden")).rejects.toBeInstanceOf(GitHubRefused);
    expect(calls).toHaveLength(0);
  });
});

describe("owner-token label writes", () => {
  it("refuse agent-build in any case, on update and on create, before anything is written", async () => {
    const { impl, calls } = fake({ "GET /repos/a/b/issues/7": { number: 7, labels: [], state: "open" } });
    const gh = owner(impl);
    await expect(gh.createIssue({ repo: "a/b", title: "t", body: "b", labels: ["Agent-Build"] }, "Aiden")).rejects.toThrow("agent-build is the owner's label");
    await expect(gh.updateIssue({ owner: "a", repo: "b", number: 7 }, { addLabels: ["agent-build"] })).rejects.toThrow("agent-build is the owner's label");
    expect(calls.filter((c) => c.method !== "GET")).toHaveLength(0);
  });
});

describe("GitHub", () => {

  it("refuses a log redirect to any other host without fetching it", async () => {
    const calls: string[] = [];
    const impl = (async (input: URL | string) => {
      calls.push(String(input));
      return new Response(null, { status: 302, headers: { location: "https://evil.example.com/log" } });
    }) as typeof fetch;
    await expect(owner(impl).jobLog("a/b", 5)).rejects.toThrow("no log download");
    expect(calls).toHaveLength(1);
  });

  describe("createIssue", () => {
    const project = {
      data: {
        organization: {
          projectV2: {
            id: "P1",
            title: "Acme Wallet",
            url: "https://github.com/orgs/example-org/projects/16",
            closed: false,
            field: { id: "F1", options: [{ id: "o1", name: "❄  Icebox" }, { id: "o2", name: "🔍  Triage" }] },
            items: { nodes: [{ content: { repository: { nameWithOwner: "example-org/issue-tracker" } } }, { content: { repository: { nameWithOwner: "example-org/issue-tracker" } } }, { content: { repository: { nameWithOwner: "example-org/other" } } }, { content: null }] },
          },
        },
      },
    };
    const created = { number: 9, node_id: "I9", html_url: "https://github.com/example-org/issue-tracker/issues/9", labels: [{ name: "waas" }] };
    /** GraphQL answers by document. */
    function gql(answers: Partial<Record<keyof typeof GRAPHQL, unknown>>, rest: Record<string, unknown> = {}) {
      const f = fake(rest);
      const impl = (async (input: URL | string, init?: RequestInit) => {
        if (new URL(String(input)).pathname !== "/graphql") return f.impl(input, init);
        const { query } = JSON.parse(String(init!.body));
        const name = (Object.keys(GRAPHQL) as (keyof typeof GRAPHQL)[]).find((k) => GRAPHQL[k] === query)!;
        f.calls.push({ method: "POST", url: new URL(String(input)), body: { doc: name, ...JSON.parse(String(init!.body)).variables } });
        return new Response(JSON.stringify(answers[name] ?? { errors: [{ message: "no" }] }), { status: 200 });
      }) as typeof fetch;
      return { impl, calls: f.calls };
    }

    it("opens the issue in the project's repository with labels and a status", async () => {
      const { impl, calls } = gql(
        { project, addItem: { data: { addProjectV2ItemById: { item: { id: "IT1" } } } }, setStatus: { data: { updateProjectV2ItemFieldValue: { projectV2Item: { id: "IT1" } } } } },
        { "GET /repos/example-org/issue-tracker/labels": [{ name: "bug" }, { name: "waas" }], "POST /repos/example-org/issue-tracker/issues": created },
      );
      const out = await owner(impl).createIssue({ title: "T", body: "B", labels: ["WaaS"], project: "https://github.com/orgs/Example-Org/projects/16/views/17", status: "triage" }, "Aiden");
      expect(out).toEqual({ repo: "example-org/issue-tracker", number: 9, url: created.html_url, labels: ["waas"], objects: ["github:example-org/issue-tracker#9"], project: { title: "Acme Wallet", url: project.data.organization.projectV2.url, added: true, status: "🔍  Triage" } });
      expect(calls.find((c) => c.url.pathname.endsWith("/issues"))?.body).toEqual({ title: "T", body: `B\n\n${FOOTER("Aiden")}`, labels: ["waas"] });
      expect(calls.at(-1)?.body).toEqual({ doc: "setStatus", project: "P1", item: "IT1", field: "F1", option: "o2" });
    });

  });

  describe("review thread replies", () => {
    const page = (nodes: unknown[], hasNextPage = false) => ({ data: { repository: { pullRequest: { reviewThreads: { pageInfo: { hasNextPage, endCursor: hasNextPage ? "C1" : null }, nodes } } } } });
    /** A comment's id arrives as `fullDatabaseId` (a BigInt, a JSON string): `databaseId` isn't read. */
    const comment = (id: number) => ({ fullDatabaseId: String(id), url: "u", body: "b", author: { __typename: "User", login: "owner1" } });
    const node = (first: number, replies: number[] = [], commentsMore = false) => ({ id: "T1", isResolved: false, isOutdated: false, viewerCanResolve: true, path: "src/a.ts", line: 3, comments: { pageInfo: { hasNextPage: commentsMore }, nodes: [first, ...replies].map(comment) } });
    /** A fake GitHub whose review threads are `threads` and whose reply write answers with `answer`. */
    function fakeThreads(threads: unknown[], answer: () => Response = () => new Response(JSON.stringify({ id: 77, html_url: "https://github.com/a/b/pull/7#discussion_r77" }), { status: 201 }), threadPages: unknown[][] = []) {
      const calls: { method: string; path: string; body?: any }[] = [];
      let read = 0;
      const impl = (async (input: URL | string, init?: RequestInit) => {
        const url = new URL(String(input));
        const method = init?.method ?? "GET";
        calls.push({ method, path: url.pathname, body: init?.body ? JSON.parse(String(init.body)) : undefined });
        if (url.pathname === "/graphql") {
          const nodes = threadPages.length ? threadPages[Math.min(read, threadPages.length - 1)]! : threads;
          const more = threadPages.length ? read < threadPages.length : false;
          read++;
          return new Response(JSON.stringify(page(nodes, more)), { status: 200 });
        }
        if (method === "POST" && /\/pulls\/7\/comments\/\d+\/replies$/.test(url.pathname)) return answer();
        return new Response("Not Found", { status: 404 });
      }) as typeof fetch;
      return { impl, calls };
    }

    it("a reply id resolves to its thread's first comment, which the POST names", async () => {
      const { impl, calls } = fakeThreads([node(100, [101, 102])]);
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 101, "fixed: abc1234.", "Aiden")).resolves.toEqual({ id: 77, url: "https://github.com/a/b/pull/7#discussion_r77" });
      const post = calls.find((c) => c.method === "POST" && c.path !== "/graphql")!;
      expect(post.path).toBe("/repos/a/b/pulls/7/comments/100/replies");
      expect(post.body.body).toContain(`fixed: abc1234.\n\n${FOOTER("Aiden")}`);
    });

    it("a thread root's id is used as it is", async () => {
      const { impl, calls } = fakeThreads([node(100, [101])]);
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "disputed: see src/a.ts:3.", "Aiden");
      expect(calls.find((c) => c.method === "POST" && c.path !== "/graphql")!.path).toBe("/repos/a/b/pulls/7/comments/100/replies");
    });

    it("resolves ids past the 32-bit range from fullDatabaseId", async () => {
      const { impl, calls } = fakeThreads([node(4_657_268_819, [4_657_373_830])]);
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 4_657_373_830, "fixed: 58099a73.", "Aiden");
      expect(calls.find((c) => c.method === "POST" && c.path !== "/graphql")!.path).toBe("/repos/a/b/pulls/7/comments/4657268819/replies");
    });

    it("a comment found on a later page of threads resolves", async () => {
      const { impl, calls } = fakeThreads([], undefined, [[node(100, [101])], [node(200, [201])]]);
      await owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 201, "fixed: abc1234.", "Aiden");
      expect(calls.find((c) => c.method === "POST" && c.path !== "/graphql")!.path).toBe("/repos/a/b/pulls/7/comments/200/replies");
    });

    it("an id on no thread of the pull request fails with its reason, and nothing is posted", async () => {
      const { impl, calls } = fakeThreads([node(100, [101])]);
      const gh = owner(impl);
      await expect(gh.reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(GitHubRefused);
      await expect(gh.reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(/comment 999 isn't on a review thread of a\/b#7/);
      expect(calls.filter((c) => c.method === "POST" && c.path !== "/graphql")).toHaveLength(0);
    });

    it("a comment past the read's pages is unknown, not reported missing, and nothing is posted", async () => {
      const pages = Array.from({ length: 10 }, (_, i) => [node(100 + i, [101 + i])]);
      const { impl, calls } = fakeThreads([], undefined, pages);
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(/couldn't confirm whether comment 999 is on a review thread of a\/b#7/);
      expect(calls.filter((c) => c.method === "POST" && c.path !== "/graphql")).toHaveLength(0);
    });

    it("a thread whose comments were cut short leaves the id unknown, not missing", async () => {
      const { impl, calls } = fakeThreads([node(100, [101], true)]);
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 999, "fixed: abc1234.", "Aiden")).rejects.toThrow(/couldn't confirm whether comment 999 is on a review thread of a\/b#7/);
      expect(calls.filter((c) => c.method === "POST" && c.path !== "/graphql")).toHaveLength(0);
    });

    it("a comment without a usable fullDatabaseId is refused, not matched as 0", async () => {
      const { impl, calls } = fakeThreads([{ ...node(100), comments: { pageInfo: { hasNextPage: false }, nodes: [{ fullDatabaseId: null, url: "u", body: "b", author: { __typename: "User", login: "owner1" } }] } }]);
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "fixed: abc1234.", "Aiden")).rejects.toThrow(/didn't return a usable review comment id/);
      expect(calls.filter((c) => c.method === "POST" && c.path !== "/graphql")).toHaveLength(0);
    });

    it("a 422 surfaces GitHub's errors[] field and code", async () => {
      const { impl } = fakeThreads([node(100)], () => new Response(JSON.stringify({ message: "Validation Failed", errors: [{ resource: "PullRequestReviewComment", field: "body", code: "custom", message: "body is too long" }] }), { status: 422 }));
      await expect(owner(impl).reply({ owner: "a", repo: "b", number: 7 }, 100, "x", "Aiden")).rejects.toThrow(/Validation Failed; PullRequestReviewComment\.body: custom: body is too long/);
    });
  });

  describe("issue, review and re-run writes", () => {
    it("pr review posts COMMENT only, at the head it read, signed by the agent", async () => {
      const { impl, calls } = fake({ "GET /repos/a/b/pulls/7": { state: "open", head: { sha: "abc" } }, "POST /repos/a/b/pulls/7/reviews": { id: 5, html_url: "h", state: "COMMENTED" } });
      const gh = owner(impl);
      await expect(gh.review({ owner: "a", repo: "b", number: 7 }, "Looks fine.", "Aiden")).resolves.toEqual({ id: 5, url: "h", state: "COMMENTED" });
      expect(calls.at(-1)?.body).toEqual({ event: "COMMENT", commit_id: "abc", body: `Looks fine.\n\n${FOOTER("Aiden")}` });
      await expect(gh.review({ owner: "a", repo: "b", number: 7 }, " ", "Aiden")).rejects.toBeInstanceOf(GitHubRefused);
    });

  });

});
